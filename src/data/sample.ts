/** Tasks marked done across all households, per day, oldest first (last 30 days). */
export const tasksDoneDaily: { day: string; count: number }[] = Array.from(
  { length: 30 },
  (_, i) => {
    const daysAgo = 29 - i;
    const weekend = new Date(NOW - daysAgo * DAY).getDay() % 6 === 0;
    // A slow climb as households join, softer on weekends.
    const base = 18 + Math.round(i * 0.9) + ((i * 7) % 5);
    return { day: ago(daysAgo), count: weekend ? Math.round(base * 0.6) : base };
  },
);

